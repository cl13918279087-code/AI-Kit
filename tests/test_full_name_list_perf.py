def generate_full_name_list(n: int = 7398) -> list[str]:
    """生成 n 条模拟全名，用于性能测试。"""
    names = set()
    rng = random.Random(42)  # 确定性种子，保证可复现
    surnames_dedup = list(dict.fromkeys(SURNAMES))  # 去重
    while len(names) < n:
        s = rng.choice(surnames_dedup)
        # 2字名或3字名
        name_len = rng.choices([2, 3], weights=[0.7, 0.3])[0]
        name = "".join(rng.choices(NAME_CHARS, k=name_len))
        names.add(s + name)
    return list(names)


