def test_regex_compile_time_longname_first(full_name_list):
    """长名优先排列：编译时间 + 正确性（长名不被短名截断）。"""
    # 长名优先（降序）
    sorted_names = sorted(full_name_list, key=len, reverse=True)
    pattern_str = "|".join(sorted_names)

    t0 = time.perf_counter()
    compiled = re.compile(pattern_str)
    compile_ms = (time.perf_counter() - t0) * 1000

    print(f"\n  [长名优先] 编译：{compile_ms:.1f}ms  pattern长度：{len(pattern_str):,}字符")

    # 正确性：长名不被截断
    # 假设有"欧阳娜娜"，短名"欧阳"不应先匹配
    assert compiled.search("欧阳娜娜") is None  # 若有欧阳娜娜，应在列表中
