    # 结论：必须长名优先
    assert m_l and m_l.group() == "张伟明", "长名优先应完整匹配"
    # 短名优先仅记录风险，不失败（取决于 full_name_list 实际数据）
    print(f"  结论：full_name_list 若无重叠短名（张伟/张伟明），短名优先无风险")


