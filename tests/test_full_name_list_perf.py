def test_match_latency_single(full_name_list):
    """单次文本匹配延迟。"""
    sorted_names = sorted(full_name_list, key=len, reverse=True)
    boundary_re = re.compile(rf"(?<![a-zA-Z0-9])({'|'.join(sorted_names)})(?![a-zA-Z0-9])")

    test_cases = [
        "负责人：张伟负责项目",
        "邹阳和陈黎参加",
        "艾成军主持会议",
        "李明在总行工作",
        "王小红同志",
    ]

    latencies = []
    for text in test_cases:
        t0 = time.perf_counter()
        for _ in range(1000):  # 单用例测1000次平滑波动
            boundary_re.findall(text)
        avg_us = (time.perf_counter() - t0) / 1000 * 1_000_000
        latencies.append(avg_us)

    avg_latency = sum(latencies) / len(latencies)
    print(f"\n  [单次匹配] 平均延迟：{avg_latency:.1f}μs  最大：{max(latencies):.1f}μs")
    assert avg_latency < 500, f"Single match too slow: {avg_latency:.1f}μs > 500μs"


