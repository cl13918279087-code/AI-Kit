    # 构造一个3字名 + 4字名共存的场景
    names = ["张伟", "张伟明"]  # 短名在前会截断长名
    # 长名优先：不会截断
    sorted_l = sorted(names, key=len, reverse=True)
    re_l = re.compile(rf"(?<![a-zA-Z0-9])({'|'.join(sorted_l)})(?![a-zA-Z0-9])")
    m_l = re_l.search("张伟明是负责人")
    print(f"\n  [长名优先] '张伟明'匹配：{'通过' if m_l else '失败'}  匹配结果：{m_l.group() if m_l else 'None'}")

    # 短名优先：会截断
    sorted_s = sorted(names, key=len)
    re_s = re.compile(rf"(?<![a-zA-Z0-9])({'|'.join(sorted_s)})(?![a-zA-Z0-9])")
    m_s = re_s.search("张伟明是负责人")
