def test_json_load_time_baseline(tmp_path, full_name_list):
    """Baseline：不含 full_name_list 的 config.json 加载时间。"""
    config = {"version": "1.0", "mask_char": "X"}
    path = tmp_path / "config_baseline.json"
    path.write_text(json.dumps(config, ensure_ascii=False), encoding="utf-8")

    times = []
    for _ in range(100):
        t0 = time.perf_counter()
        with open(path, encoding="utf-8") as f:
            json.load(f)
        times.append(time.perf_counter() - t0)

    avg = sum(times) / len(times)
    p95 = sorted(times)[int(len(times) * 0.95)]
    print(f"\n  [Baseline] JSON load avg={avg*1000:.3f}ms  p95={p95*1000:.3f}ms")
    assert avg < 0.1, f"Baseline JSON load too slow: {avg*1000:.3f}ms > 100ms"


